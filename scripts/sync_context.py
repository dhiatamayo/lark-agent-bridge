"""Generate an AGENTS.md from a directory of context/steering markdown files.

Some agent CLIs read per-tool context files automatically (e.g. Kiro reads
``.kiro/steering/*.md``), while others read a single ``AGENTS.md`` at the
workspace root. This script concatenates a directory of markdown files (with
their YAML frontmatter stripped) into one ``AGENTS.md`` so every engine shares
the same context from a single source of truth.

Usage:
    python scripts/sync_context.py --src .kiro/steering --out AGENTS.md

Run it whenever the source files change.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

FRONTMATTER_RE = re.compile(r"^---\n.*?\n---\n", re.S)


def strip_frontmatter(text: str) -> str:
    """Remove a leading ``--- ... ---`` YAML frontmatter block if present."""
    return FRONTMATTER_RE.sub("", text, count=1).lstrip("\n")


def build(src: Path, order: list[str]) -> tuple[str, list[Path]]:
    # Honour the requested order first, then append any other *.md (future-proof).
    files = [src / name for name in order if (src / name).exists()]
    for extra in sorted(src.glob("*.md")):
        if extra not in files:
            files.append(extra)

    parts = [
        "# AGENTS.md — shared agent context (auto-generated)\n",
        "> Generated by scripts/sync_context.py. DO NOT edit here; edit the\n"
        f"> source files in `{src}` and re-run the script.\n",
    ]
    for f in files:
        body = strip_frontmatter(f.read_text(encoding="utf-8")).rstrip()
        parts.append(f"\n\n---\n\n<!-- from {f.name} -->\n\n{body}\n")
    return "".join(parts), files


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate AGENTS.md from a markdown context directory.")
    parser.add_argument("--src", default=".kiro/steering", help="source directory of *.md files")
    parser.add_argument("--out", default="AGENTS.md", help="output file path")
    parser.add_argument("--order", nargs="*", default=[],
                        help="optional ordered filenames to place first")
    args = parser.parse_args()

    src = Path(args.src)
    if not src.is_dir():
        parser.error(f"source directory not found: {src}")
    out = Path(args.out)

    content, files = build(src, args.order)
    out.write_text(content, encoding="utf-8")
    print(f"Wrote {out} ({out.stat().st_size} bytes) from {len(files)} files:")
    for f in files:
        print(f"  - {f.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
