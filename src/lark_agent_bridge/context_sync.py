"""Generate ``AGENTS.md`` from a directory of steering/context markdown files.

Some agent CLIs read per-tool context files automatically (e.g. Kiro reads
``.kiro/steering/*.md``), while others read a single ``AGENTS.md`` at the
workspace root. This module concatenates a directory of markdown files (with
their YAML frontmatter stripped) into one ``AGENTS.md`` so every engine shares
the same context from a single source of truth.

It is the single canonical implementation, used both by
``scripts/sync_context.py`` (manual CLI) and by the bot's per-message
refresh-on-change so the file never drifts behind the steering sources.
"""

from __future__ import annotations

import re
from pathlib import Path

FRONTMATTER_RE = re.compile(r"^---\n(.*?)\n---\n", re.S)


def is_manual_inclusion(text: str) -> bool:
    """Check if the YAML frontmatter explicitly sets ``inclusion: manual``."""
    m = FRONTMATTER_RE.match(text)
    if m and re.search(r"^inclusion:\s*manual", m.group(1), re.M):
        return True
    return False


def strip_frontmatter(text: str) -> str:
    """Remove a leading ``--- ... ---`` YAML frontmatter block if present."""
    return FRONTMATTER_RE.sub("", text, count=1).lstrip("\n")


def build(src: Path, order: list[str] | None = None) -> tuple[str, list[Path]]:
    """Concatenate ``src/*.md`` into one markdown string.

    Files in *order* come first (when present), then any remaining ``*.md`` in
    sorted order (future-proof). Files whose frontmatter sets
    ``inclusion: manual`` are skipped. Returns ``(content, files_used)``.
    """
    order = order or []
    candidate_files = [src / name for name in order if (src / name).exists()]
    for extra in sorted(src.glob("*.md")):
        if extra not in candidate_files:
            candidate_files.append(extra)

    files: list[Path] = []
    parts = [
        "# AGENTS.md — shared agent context (auto-generated)\n",
        "> Generated by scripts/sync_context.py. DO NOT edit here; edit the\n",
        f"> source files in `{src}` and re-run the script.\n",
    ]
    for f in candidate_files:
        raw = f.read_text(encoding="utf-8")
        if is_manual_inclusion(raw):
            continue
        files.append(f)
        body = strip_frontmatter(raw).rstrip()
        parts.append(f"\n\n---\n\n<!-- from {f.name} -->\n\n{body}\n")
    return "".join(parts), files


def write_atomic(path: Path, content: str) -> None:
    """Write *content* to *path* atomically (temp file + rename)."""
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(content, encoding="utf-8")
    tmp.replace(path)
